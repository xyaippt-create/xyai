MAX_BYTES = 50 * 1024 * 1024
MAX_PIXELS = 80_000_000
MAX_SIDE = 32_768
EXTENSIONS = {"JPEG": ".jpg", "PNG": ".png", "WEBP": ".webp"}
log = logging.getLogger(__name__)


def _owned_path(path, root):
    if root not in path.parents or path.resolve() != path:
        raise HTTPException(409, "喷绘目录或文件路径已改变，请检查正式目录。")
    return path


def _new_target(directory, name, registry):
    # An interrupted publication still owns its filename even when the rename
    # has not yet happened. Other requests can continue under the next suffix.
    reserved = {Path(record["print_target"]) for record in registry.values()
                if record.get("record_kind") == "print_publication" and record.get("print_target")}
    moment = datetime.now()
    sequence = 1
    while True:
        leaf = build_output_filename(name, FEATURE_PRINT, ".png", moment=moment,
                                     sequence=sequence if sequence > 1 else None)
        target = directory / leaf
        if target not in reserved and not os.path.lexists(target):
            return target
        sequence += 1


@contextmanager
def _render_slot(directory):
    # One render per formal root, including across desktop instances. The OS
    # releases the lock on exit, so an interrupted request can resume.
    with _owned_path(directory / ".render.lock", directory).open("a+b") as handle:
        handle.seek(0)
        try:
            if os.name == "nt":
                import msvcrt
                msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl
                fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as exc:
            raise HTTPException(409, "当前正在生成另一张喷绘成品，请稍后重试。") from exc
        yield


def _png_options(image, ext, ppi):
    options = {"dpi": (ppi, ppi), "icc_profile": image.info.get("icc_profile")}
    if ext == ".png":
        chunks = PngImagePlugin.PngInfo()
        if not options["icc_profile"]:
            # Untagged pixels are sRGB by convention; say so for the print RIP.
            chunks.add(b"sRGB", bytes([image.info.get("srgb", 0)]))
        if "gamma" in image.info:
            chunks.add(b"gAMA", round(image.info["gamma"] * 100000).to_bytes(4, "big"))
        if "chromaticity" in image.info:
            chunks.add(b"cHRM", struct.pack(">8I", *(round(v * 100000) for v in image.info["chromaticity"])))
        options["pnginfo"] = chunks
    return options


def _upscale(converted, size, work_dir):
    """Reconstruct detail with the 4K engine before enlarging colour images; LANCZOS otherwise."""
    plan = plan_print_upscale(converted.width, converted.height, *size, color=converted.mode in ("RGB", "RGBA"))
    if plan["method"] != "SR_FUSION":
        return converted.resize(size, Image.Resampling.LANCZOS), {"method": "LANCZOS", "reason": plan["reason"]}
    alpha = converted.getchannel("A") if converted.mode == "RGBA" else None
    rgb = _fill_transparent_rgb(converted.convert("RGB"), alpha) if alpha else converted
    try:
        resized, info = upscale_rgb_for_print(rgb, size, work_dir, plan)
    except FourKV1ProcessingError as exc:
        raise HTTPException(503, f"喷绘超清未完成：{exc}") from exc
    if alpha:
        # Alpha is never generated by SR; it is enlarged from the original.
        resized.putalpha(alpha.resize(size, Image.Resampling.LANCZOS))
    return resized, info


def _render(data, width, height, ppi, work_dir):
    try:
        with Image.open(BytesIO(data), formats=list(EXTENSIONS)) as original:
            ext = EXTENSIONS[original.format]
            if original.width * original.height > MAX_PIXELS or getattr(original, "n_frames", 1) > 1:
                raise HTTPException(422, "请选择不超过 8000 万像素的单帧图片。")
            if original.mode == "CMYK" or (ext == ".png" and data[24] == 16):
                raise HTTPException(422, "请先将原图转换成 8 位 RGB 或灰度图片后再出图。")
            with ImageOps.exif_transpose(original) as upright:
                sw, sh = upright.size
                if abs(width * sh - height * sw) >= max(sw, sh):
                    raise HTTPException(422, "目标宽高与原图比例不符，请重新预检。")
                alpha = "A" in upright.getbands() or "transparency" in upright.info
                gray = upright.mode in ("1", "L", "LA")
                mode = ("LA" if alpha else "L") if gray else ("RGBA" if alpha else "RGB")
                # A keyed grayscale PNG needs expansion through RGBA before LA.
                converted = upright.convert("RGBA").convert("LA") if gray and "transparency" in upright.info else upright.convert(mode)
                with converted:
                    converted.load()
                    resized, upscale = _upscale(converted, (width, height), work_dir)
                with resized:
                    resized.info.clear()
                    encoded = BytesIO()
                    resized.save(encoded, format="PNG", **_png_options(upright, ext, ppi))
    except (OSError, SyntaxError, ValueError, Image.DecompressionBombError) as exc:
        raise HTTPException(422, "图片无法完整解码，请重新选择 JPG、PNG 或 WebP 图片。") from exc
    output, _ = write_hdde_metadata_bytes(encoded.getvalue())
    return output, ext, sw, sh, upscale


def register_print_output_routes(app, *, user_dirs_provider, registry):
    def read_source(file, result_id, root=None):
        if (file is not None) == bool(result_id):
            raise HTTPException(422, "请选择一张本地图片或一个已有成品。")
        if file is not None:
            if file.size is not None and file.size > MAX_BYTES:
                raise HTTPException(413, "喷绘原图最多 50 MiB。")
            data = file.file.read(MAX_BYTES + 1)
            if len(data) > MAX_BYTES:
                raise HTTPException(413, "喷绘原图最多 50 MiB。")
            return data, Path(file.filename or "图片").name, {}
        try:
            source = resolve_reusable_result_source(
                registry, result_id, root or Path(user_dirs_provider()["app_data_root"]),
                max_bytes=MAX_BYTES, allowed_suffixes={".jpg", ".jpeg", ".png", ".webp"},
            )
            with source["source_result_path"].open("rb") as stream:
                data = stream.read(MAX_BYTES + 1)
        except ResultReuseError as exc:
            raise HTTPException(exc.status_code, detail={"code": exc.code, "message": exc.message}) from exc
        except OSError as exc:
            raise HTTPException(409, "已有成品无法读取，请返回输出中心检查文件。") from exc
        if hashlib.sha256(data).hexdigest() != source["source_result_sha256"]:
            raise HTTPException(409, "已有成品内容已改变，请返回输出中心重新选择。")
        return data, source["source_result_file_name"], result_lineage_fields(source)

    @app.post("/api/print-output/layers/preview")
    def preview_layers(file: UploadFile | None = File(None), layers: str = Form(...), result_id: str = Form("")):
        data, _, _ = read_source(file, result_id)
        try:
            recipe = Recipe.read(layers)
            rgb, _ = read_poster(data)
            h, w = rgb.shape[:2]
            ratio = min(1, 1000 / max(w,h))
            preview, info = compose(rgb, recipe, (max(1,round(w*ratio)),max(1,round(h*ratio))), overlay=True)
            buf=BytesIO()
            preview.save(buf,format="PNG")
            return {**info, "recipe":recipe.model_dump(mode="json"), "source_sha256":hashlib.sha256(data).hexdigest(),
                    "preview":"data:image/png;base64,"+base64.b64encode(buf.getvalue()).decode("ascii")}
        except LayerError as exc:
            raise HTTPException(422, str(exc)) from exc

    @app.post("/api/print-output/render")
    def render_print(file: UploadFile | None = File(None), width: int = Form(...), height: int = Form(...),
                     ppi: float = Form(...), request_id: UUID = Form(...), layers: str = Form(""),
                     source_result_id: str = Form("", alias="result_id")):
        if min(width, height) < 1 or max(width, height) > MAX_SIDE or width * height > MAX_PIXELS:
            raise HTTPException(422, "目标尺寸超出范围。单边最多 32768 px，总像素最多 8000 万。")
        if not math.isfinite(ppi) or not 0.0254 <= ppi <= 0xffffffff * 0.0254:
            raise HTTPException(422, "目标 PPI 超出 PNG 精度范围，请调整数值。")
        dirs = user_dirs_provider()
        root = Path(dirs["app_data_root"]).resolve()
        source_dir = _owned_path(Path(dirs["normal_input_dir"]) / "喷绘出图", root)
        output_dir = _owned_path(Path(dirs["output_root"]) / "喷绘出图", root)
        registry_path = getattr(registry, "path", None)
        if registry_path and root not in registry_path.parents:
            raise HTTPException(409, "正式目录已切换，请重新启动后生成喷绘成品。")
        task_id = f"print_{request_id.hex}"
        try:
            source_dir.mkdir(parents=True, exist_ok=True)
            with _render_slot(source_dir):
                data, name, lineage = read_source(file, source_result_id, root)
                source_sha = hashlib.sha256(data).hexdigest()
                spec = {"width": width, "height": height, "ppi": ppi, "sha256": source_sha, "name": name}
                if lineage:
                    spec["source_result_id"] = lineage["source_result_id"]
                recipe = Recipe.read(layers) if layers else None
                if recipe:
                    spec["layers"] = recipe.model_dump(mode="json")
                prior = registry.get(task_id)
                if prior and prior.get("print_spec") != spec:
                    raise HTTPException(409, "该请求已用于其他喷绘规格，请重新预检。")
                if prior and prior.get("status") == "completed":
                    path = _owned_path(Path(prior["result_file"]), output_dir)
                    if not path.is_file() or sha256_file(path) != prior["output_sha256"]:
                        raise HTTPException(409, "已生成的喷绘成品已移动或改变，请重新选择原图出图。")
                    return prior["print_response"]

                layer_info = upscale = None
                if recipe:
                    rgb, ext = read_poster(data)
                    sh, sw = rgb.shape[:2]
                    poster, layer_info = compose(rgb, recipe, (width,height), source_dir)
                    encoded = BytesIO()
                    color_chunks=PngImagePlugin.PngInfo()
                    color_chunks.add(b"sRGB",b"\x00")
                    poster.save(encoded,format="PNG",dpi=(ppi,ppi),pnginfo=color_chunks)
                    poster.close()
                    output, _ = write_hdde_metadata_bytes(encoded.getvalue())
                else:
                    output, ext, sw, sh, upscale = _render(data, width, height, ppi, source_dir)
                source = _owned_path(source_dir / (source_sha + ext), source_dir)
                if not source.exists():
                    publish_prepared_bytes_no_overwrite(data, [source])
                if sha256_file(source) != source_sha:
                    raise HTTPException(409, "正式原图与本次输入不一致，已暂停出图。")
                output_dir.mkdir(parents=True, exist_ok=True)
                output_sha = hashlib.sha256(output).hexdigest()
                if prior:
                    target = _owned_path(Path(prior["print_target"]), output_dir)
                    if prior["output_sha256"] != output_sha:
                        raise HTTPException(409, "本次渲染与中断前的结果不同，请重新选择原图出图。")
                else:
                    target = _new_target(output_dir, name, registry)
                    prior = {
                        **new_operation_identity(FEATURE_PRINT, module_id="hdde.print.output"),
                        **lineage,
                        "task_id": task_id, "record_kind": "print_publication", "status": "pending", "print_spec": spec,
                        "created_at": datetime.now().astimezone().isoformat(), "original_filename": name,
                        "source_path": str(source), "source_sha256": source_sha,
                        "mode": FEATURE_PRINT, "input_format": ext[1:].upper(), "output_format": "PNG",
                        "input_size_bytes": len(data), "output_size_bytes": len(output),
                        "input_width": sw, "input_height": sh, "output_width": width, "output_height": height,
                        "output_sha256": output_sha, "print_target": str(target),
                    }
                    registry[task_id] = prior
                if target.exists():
                    if sha256_file(target) != output_sha:
                        raise HTTPException(409, "目标文件已被占用，请重新选择图片出图。")
                else:
                    publish_prepared_bytes_no_overwrite(output, [target])
                result_id = f"print_result_{request_id.hex}"
                response = {"result_id": result_id, "task_id": task_id, "filename": target.name,
                            "width": width, "height": height, "ppi": ppi,
                            "preview_url": f"/api/v1/tasks/{task_id}/result-file"}
                if layer_info:
                    response["layers"] = layer_info
                if upscale:
                    response["upscale"] = upscale
                registry[task_id] = {
                    **prior, "record_kind": "task", "status": "completed", "task_status": "completed", "progress": 100,
                    "completed_at": datetime.now().astimezone().isoformat(),
                    "result_id": result_id, "result_file": str(target), "output_path": str(target),
                    "delivery_eligible": True, "print_response": response,
                }
                return response
        except LayerError as exc:
            raise HTTPException(422, str(exc)) from exc
        except (OSError, RuntimeError, ValueError) as exc:
            log.exception("Print output failed for task %s", task_id)
            raise HTTPException(500, "喷绘成品未能完成登记，请检查正式目录和剩余空间后重试。") from exc
